export function generateOperatingHours(): string[] {
  const hours: string[] = [];
  // Turno da Manhã (07:00 até 11:30)
  for (let h = 7; h <= 11; h++) {
    hours.push(`${String(h).padStart(2, '0')}:00`);
    hours.push(`${String(h).padStart(2, '0')}:30`);
  }
  // Turno da Tarde/Noite (13:00 até 20:00)
  for (let h = 13; h <= 19; h++) {
    hours.push(`${String(h).padStart(2, '0')}:00`);
    hours.push(`${String(h).padStart(2, '0')}:30`);
  }
  hours.push("20:00");
  return hours;
}

